import math

N = 1_000_000  # Для исходного ряда
M = 1500       # Для первого улучшения
L = 87         # Для второго улучшения
eps = 1e-6     # Точность

# Без ускорения
print(f"1. Исходный ряд (N = {N}):")
S_N = 0.0
for n in range(1, N + 1):
    a_n = (n**2 - 1.3*n - 1) / (n**4 + 1)
    S_N += a_n
print(f"   Сумма S_N = {S_N:.10f}")
print(f"   Погрешность метода A_a* <= 1/N = {1/N:.1e}\n")


# Первое улучшение
print(f"2. Первое улучшение (M = {M}):")
P_M = 0.0
for n in range(1, M + 1):
    a_n = (n**2 - 1.3*n - 1) / (n**4 + 1)
    b_n = 1 / (n**2)
    p_n = a_n - b_n
    P_M += p_n

B_1 = (math.pi**2) / 6
S_M = B_1 + P_M

print(f"Сумма остатка P_M = {P_M:.10f}")
print(f"Сумма эталонного ряда B_1 = {B_1:.10f}")
print(f"Итоговая сумма S_M = B_1 + P_M = {S_M:.10f}")
print(f"Погрешность метода A_p* <= 1/(M+1)^2 = {1/((M+1)**2):.1e}\n")


# Второе улучшение
print(f"3. Второе улучшение (L = {L}):")
Q_L = 0.0
for n in range(1, L + 1):
    a_n = (n**2 - 1.3*n - 1) / (n**4 + 1)
    c_n = (1 / (n**2)) - (1.3 / (n**3))
    q_n = a_n - c_n
    Q_L += q_n
zeta_3 = 1.2020569031595942
B_2 = (math.pi**2)/6 - 1.3 * zeta_3
S_L = B_2 + Q_L

print(f"Сумма остатка Q_L = {Q_L:.10f}")
print(f"Сумма эталонного ряда B_2 = {B_2:.10f}")
print(f"Итоговая сумма S_L = B_2 + Q_L = {S_L:.10f}")
print(f"Погрешность метода A_q* <= 2/(3*(L+1)^3) = {2/(3*((L+1)**3)):.1e}\n")

print(f"Исходная сумма (N=1e6):  {S_N:.6f}")
print(f"1-е улучшение (M=1500):  {S_M:.6f}")
print(f"2-е улучшение (L=88):    {S_L:.6f}")

